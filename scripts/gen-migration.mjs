// Turns drizzle/0000_init.sql into src/db/migration-sql.ts. Every statement is idempotent, so bootstrap can create only what is missing.
import fs from "node:fs";
const sql = fs.readFileSync("drizzle/0000_init.sql", "utf8");
const stmts = sql.split("--> statement-breakpoint").map((x) => x.trim()).filter(Boolean)
  .map((x) => x.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ").replace(/^CREATE INDEX /, "CREATE INDEX IF NOT EXISTS ").replace(/^CREATE UNIQUE INDEX /, "CREATE UNIQUE INDEX IF NOT EXISTS "));
fs.writeFileSync("src/db/migration-sql.ts", `// Generated by scripts/gen-migration.mjs from the Drizzle schema (npm run db:sql). Do not edit by hand.\nexport const MIGRATION: string[] = ${JSON.stringify(stmts, null, 1)};\n`);
console.log(stmts.length, "statements");
