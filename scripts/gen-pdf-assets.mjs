// Embeds the PDF fonts and logo as base64 so PDF generation never depends on files being present on the server.
import fs from "node:fs";
const dir = "src/pdf/assets";
const b64 = (f, mime) => `data:${mime};base64,${fs.readFileSync(`${dir}/${f}`).toString("base64")}`;
const out = `// Generated by scripts/gen-pdf-assets.mjs. Do not edit by hand.
export const FONTS = {
  inter400: "${b64("inter-latin-400-normal.woff", "font/woff")}",
  inter600: "${b64("inter-latin-600-normal.woff", "font/woff")}",
  inter700: "${b64("inter-latin-700-normal.woff", "font/woff")}",
  brico700: "${b64("bricolage-grotesque-latin-700-normal.woff", "font/woff")}",
  brico800: "${b64("bricolage-grotesque-latin-800-normal.woff", "font/woff")}",
};
export const LOGO_DATA = "${b64("logo.png", "image/png")}";
`;
fs.writeFileSync("src/pdf/assets.generated.ts", out);
console.log("ok", Math.round(out.length / 1024), "KB");
